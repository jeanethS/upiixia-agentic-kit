#!/usr/bin/env python3
"""Draw the claims protocol from TLC: python3 scripts/tla_statechart.py [--out docs/tla/statechart.md]

The chart is TLC's whole state graph for one task (docs/tla/ClaimsChart.cfg) projected on that task's State, so it
cannot drift from the model. The counterexample is TLC's trace for docs/tla/ClaimsBroken.cfg; TLC searches
breadth-first, so it is a shortest one. Needs what scripts/tla_check.sh needs (Java, the pinned jar)."""
import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TLA = REPO / "docs" / "tla"
ORDER = ["AVAILABLE", "CLAIMED", "REVIEW", "INTEGRATED"]


def tlc(cfg, extra=""):
    env = dict(os.environ, UAK_TLC_WORKERS="1", UAK_TLC_ARGS=extra)
    return subprocess.run(["bash", str(REPO / "scripts" / "tla_check.sh"), str(cfg)], env=env,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)


def rank(state):
    return (ORDER.index(state) if state in ORDER else len(ORDER), state)


def chart():
    with tempfile.TemporaryDirectory() as tmp:
        dot = Path(tmp) / "graph.dot"
        out = tlc(TLA / "ClaimsChart.cfg", "-dump dot,actionlabels " + str(dot))
        if out.returncode != 0:
            sys.exit("TLC failed on ClaimsChart.cfg:\n" + out.stdout[-3000:])
        text = dot.read_text(encoding="utf-8")
    state, initial = {}, set()
    for m in re.finditer(r'^(-?\d+) \[label="((?:[^"\\]|\\.)*)"(.*)$', text, re.M):
        st = re.search(r'st = \(t1 :> \\"(\w+)\\"\)', m.group(2))
        state[m.group(1)] = st.group(1)
        if "filled" in m.group(3):
            initial.add(st.group(1))
    moves = {}
    for m in re.finditer(r'^(-?\d+) -> (-?\d+) \[label="(\w+)"', text, re.M):
        a, b = state[m.group(1)], state[m.group(2)]
        if a != b:
            moves.setdefault((a, b), set()).add(m.group(3))
    lines = ["stateDiagram-v2"] + ["    [*] --> %s" % s for s in sorted(initial, key=rank)]
    for (a, b) in sorted(moves, key=lambda k: (rank(k[0]), rank(k[1]))):
        lines.append("    %s --> %s : %s" % (a, b, ", ".join(sorted(moves[a, b]))))
    final = sorted({s for s in state.values()} - {a for a, _ in moves}, key=rank)
    lines += ["    %s --> [*]" % s for s in final]
    return "\n".join(lines)


def field(block, name):
    m = re.search(r"^/\\ %s = (.*?)(?=^/\\ |\Z)" % name, block, re.M | re.S)
    return re.sub(r"\s+", " ", m.group(1)).strip() if m else ""


def per_agent(value):
    parts = re.split(r"\b(a\d+) :>", value)
    return dict(zip(parts[1::2], parts[2::2]))


def counterexample():
    out = tlc(TLA / "ClaimsBroken.cfg")
    broken = re.search(r"Invariant (\w+) is violated", out.stdout)
    if out.returncode == 0 or not broken:
        sys.exit("ClaimsBroken.cfg must give a counterexample:\n" + out.stdout[-3000:])
    steps = re.findall(r"^State \d+: <(\w+)[^\n]*\n(.*?)(?=^State \d+: |^\d+ states generated|\Z)",
                       out.stdout, re.M | re.S)
    lines, before = ["flowchart LR"], None
    for i, (action, block) in enumerate(steps, 1):
        now = int(field(block, "now") or 0)
        st = dict(re.findall(r'(t\d+) :> "(\w+)"', field(block, "st")))
        own = dict(re.findall(r'(t\d+) :> "?(\w+)"?', field(block, "own")))
        works = ["%s works on %s" % (a, t) for a, v in sorted(per_agent(field(block, "belief")).items())
                 for t, until in re.findall(r"(t\d+) :> (\d+)", v) if int(until) > now]
        tasks = ["%s %s%s" % (t, st[t], "" if own.get(t, "none") == "none" else " owner " + own[t]) for t in sorted(st)]
        text = "<br/>".join(["now %d" % now] + tasks + works)
        if i == len(steps):
            text += "<br/><b>%s is violated</b>" % broken.group(1)
        lines.append('    s%d["%s"]' % (i, text))
        snap, belief = per_agent(field(block, "snap")), per_agent(field(block, "belief"))
        if before:
            who = sorted(a for a in snap if snap[a] != before[0].get(a) or belief.get(a) != before[1].get(a))
            lines.append("    s%d -->|%s| s%d" % (i - 1, " ".join(who + [action]), i))
        before = (snap, belief)
    return "\n".join(lines), broken.group(1)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(TLA / "statechart.md"))
    args = parser.parse_args()
    path, invariant = counterexample()
    doc = """# The claims protocol, drawn from the model

Generated by `python3 scripts/tla_statechart.py` from TLC's output; do not edit by hand. The tla workflow
regenerates it and fails when it differs, so the picture cannot drift from `Claims.tla`.

## A task's states

TLC's whole state graph for one task and two agents (`ClaimsChart.cfg`), projected on the task's State. An arrow
lists every action that makes that change. BLOCKED and CANCELLED are not in the model.

```mermaid
%s
```

## The shortest way to break it

`ClaimsBroken.cfg` drops the push's tip check. TLC searches breadth-first, so this is a shortest trace to a state
where %s is violated. Each arrow is one step: the agents whose clone or belief changed, then the action.

```mermaid
%s
```
""" % (chart(), invariant, path)
    Path(args.out).write_text(doc, encoding="utf-8")


if __name__ == "__main__":
    main()
